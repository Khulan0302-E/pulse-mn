-- ---------- Туслах функцууд (RLS-д ашиглана) ----------

create or replace function public.my_profile_id() returns bigint
language sql stable security definer set search_path = public as $$
  select id from public.profiles where auth_id = auth.uid() and status = 'active'
$$;

create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from public.profiles where auth_id = auth.uid() and status = 'active'
$$;

-- Хамгийн сүүлийн баталгаажуулалт нь «approved» эсэх
create or replace function public.is_verified_journalist() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((
    select v.status = 'approved'
    from public.verifications v
    where v.user_id = public.my_profile_id()
    order by v.id desc
    limit 1
  ), false)
$$;

create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.my_role() in ('editor', 'admin'), false)
$$;

-- Шинэ хэрэглэгч бүртгүүлэхэд profile автоматаар үүснэ.
-- Бүртгэлээр зөвхөн «journalist» эсвэл «citizen» роль авна; редактор, админыг админ томилно.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (auth_id, full_name, email, phone, role, org)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), split_part(new.email, '@', 1)), 100),
    lower(new.email),
    nullif(new.raw_user_meta_data ->> 'phone', ''),
    case when new.raw_user_meta_data ->> 'role' = 'journalist' then 'journalist' else 'citizen' end,
    left(coalesce(new.raw_user_meta_data ->> 'org', ''), 150)
  );
  return new;
end
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Товлох огноо өнгөрсөн байж болохгүй (FR-EDT-004)
create or replace function public.check_schedule() returns trigger
language plpgsql as $$
begin
  if new.status = 'scheduled'
     and (tg_op = 'INSERT' or new.scheduled_at is distinct from old.scheduled_at or old.status <> 'scheduled')
     and (new.scheduled_at is null or new.scheduled_at <= now()) then
    raise exception 'Товлох огноо өнгөрсөн байж болохгүй.';
  end if;
  return new;
end
$$;

drop trigger if exists news_check_schedule on public.news;
create trigger news_check_schedule
  before insert or update on public.news
  for each row execute function public.check_schedule();

-- Нийтэд үзэлт тоолох (нэвтрээгүй хэрэглэгч ч дуудаж болно)
create or replace function public.increment_view(p_id bigint) returns void
language sql security definer set search_path = public as $$
  update public.news set views = views + 1 where id = p_id and status = 'published'
$$;

-- Товлосон цаг болсон нийтлэлийг нийтлэх (cron.sql-ээс минут тутам дуудна)
create or replace function public.publish_due_news() returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  with due as (
    update public.news
       set status = 'published', published_at = now(), updated_at = now()
     where status = 'scheduled' and scheduled_at <= now()
    returning id, journalist_id, title
  ), notes as (
    insert into public.notifications (id, user_id, news_id, content)
    select (extract(epoch from clock_timestamp()) * 1000000)::bigint + row_number() over (), journalist_id, id,
           'Таны «' || title || '» нийтлэл товлосон цагтаа нийтлэгдлээ.'
      from due
    returning 1
  )
  select count(*) into n from notes;
  return n;
end
$$;

-- Олон нийтэд харагдах зохиогчийн мэдээлэл (и-мэйл, утас ороогүй — NFR-SEC-001)
create or replace view public.authors as
  select id, full_name, org, role, status, created_at
    from public.profiles
   where role <> 'citizen';

