-- ---------- Хүснэгтүүд ----------

-- Хэрэглэгч. Нууц үгийг Supabase Auth (auth.users) bcrypt-ээр хэшлэж хадгална (NFR-SEC-006).
create table if not exists public.profiles (
  id          bigint generated by default as identity primary key,
  auth_id     uuid not null unique references auth.users (id) on delete cascade,
  full_name   varchar(100) not null,
  email       varchar(100) not null unique,
  phone       varchar(8) check (phone is null or phone ~ '^[0-9]{8}$'),
  role        text not null default 'citizen' check (role in ('journalist', 'editor', 'admin', 'citizen')),
  org         varchar(150) not null default '',
  status      text not null default 'active' check (status in ('active', 'suspended')),
  created_at  timestamptz not null default now()
);

-- Сэтгүүлчийн баталгаажуулалт (FR-AUTH-001)
create table if not exists public.verifications (
  id           bigint primary key,
  user_id      bigint not null references public.profiles (id) on delete cascade,
  doc_type     text not null check (doc_type in ('org_id', 'msne', 'diploma')),
  file_url     text,
  file_name    text,
  status       text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reviewer_id  bigint references public.profiles (id),
  decided_at   timestamptz,
  reason       varchar(500) not null default '',
  created_at   timestamptz not null default now(),
  check (status <> 'rejected' or length(trim(reason)) > 0)
);

create table if not exists public.categories (
  id    int primary key,
  name  varchar(100) not null unique
);

create table if not exists public.locations (
  id     int primary key,
  aimag  varchar(50) not null,
  sum    varchar(50) not null,
  unique (aimag, sum)
);

-- Мэдээ (ноорог / нийтлэл)
create table if not exists public.news (
  id                  bigint primary key,
  journalist_id       bigint not null references public.profiles (id),
  title               varchar(200) not null check (length(trim(title)) > 0),
  content             text not null check (length(trim(content)) > 0),
  category_id         int not null references public.categories (id),
  location_id         int not null references public.locations (id),
  status              text not null default 'draft'
                      check (status in ('draft', 'review', 'returned', 'rejected', 'approved', 'scheduled', 'published')),
  version             int not null default 1 check (version >= 1),
  source              varchar(500) not null default '',
  source_confidential boolean not null default false,
  copyright_consent   boolean not null default false,
  created_at          timestamptz not null default now(),
  submitted_at        timestamptz,
  scheduled_at        timestamptz,
  published_at        timestamptz,
  updated_at          timestamptz not null default now(),
  views               int not null default 0,
  -- Зохиогчийн эрхийн зөвшөөрөлгүйгээр илгээх боломжгүй (FR-CNT-001)
  constraint news_consent_required check (status = 'draft' or copyright_consent),
  -- Нийтлэл бүр эх сурвалжтай (NFR-TRN-002)
  constraint news_source_required check (status <> 'published' or source_confidential or length(trim(source)) > 0)
);

create table if not exists public.media (
  id        bigint primary key,
  news_id   bigint not null references public.news (id) on delete cascade,
  type      text not null check (type in ('image', 'video')),
  name      text,
  file_url  varchar(500) not null unique,
  size_mb   double precision not null default 0
);

-- Редакцийн шийдвэр (FR-EDT-004)
create table if not exists public.decisions (
  id          bigint primary key,
  news_id     bigint not null references public.news (id) on delete cascade,
  version     int not null,
  editor_id   bigint not null references public.profiles (id),
  decision    text not null check (decision in ('approve', 'return', 'reject')),
  comment     varchar(1000) not null default '',
  checks      jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now(),
  -- Буцаах, татгалзах шийдвэр тайлбартай байна
  constraint decisions_comment_required check (decision = 'approve' or length(trim(comment)) > 0)
);

-- Мэдээний хувилбар — өөрчлөлтийн түүх (NFR-DAT-001)
create table if not exists public.news_versions (
  id          bigint primary key,
  news_id     bigint not null references public.news (id) on delete cascade,
  version     int not null,
  user_id     bigint not null references public.profiles (id),
  created_at  timestamptz not null default now(),
  snapshot    jsonb not null
);

create table if not exists public.notifications (
  id          bigint primary key,
  user_id     bigint not null references public.profiles (id) on delete cascade,
  news_id     bigint references public.news (id) on delete set null,
  content     varchar(1000) not null,
  created_at  timestamptz not null default now(),
  read        boolean not null default false
);

-- Гадаад мэдээлэл: цаг агаар, валютын ханш (FR-INT-001)
create table if not exists public.external_data (
  id           bigint primary key,
  type         text not null check (type in ('weather', 'fx')),
  key          varchar(50) not null,
  value        varchar(200) not null,
  temp         double precision,
  code         int,
  condition    text,
  source       varchar(100) not null,
  source_date  text,
  fetched_at   timestamptz not null default now()
);

-- API тохиргоо (нэг мөр). Анхаар: энд хадгалсан утгыг хэн ч уншиж чадна — нууц түлхүүр бүү хадгал.
