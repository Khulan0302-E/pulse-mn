-- profiles: өөрийгөө, редактор/админ бүгдийг харна. Зөвхөн админ бусдын роль, төлвийг өөрчилнө.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select
  using (auth_id = auth.uid() or public.is_staff());
drop policy if exists profiles_update on public.profiles;
create policy profiles_update on public.profiles for update
  using (public.my_role() = 'admin' and auth_id <> auth.uid())
  with check (public.my_role() = 'admin' and auth_id <> auth.uid());

-- verifications
drop policy if exists verifications_select on public.verifications;
create policy verifications_select on public.verifications for select
  using (user_id = public.my_profile_id() or public.is_staff());
drop policy if exists verifications_insert on public.verifications;
create policy verifications_insert on public.verifications for insert
  with check (user_id = public.my_profile_id() and status = 'pending' and public.my_role() = 'journalist');
drop policy if exists verifications_update on public.verifications;
-- Сэтгүүлчийн баримтыг Редактор баталгаажуулна
create policy verifications_update on public.verifications for update
  using (public.my_role() = 'editor') with check (public.my_role() = 'editor');

-- categories, locations: бүгд уншина
drop policy if exists categories_select on public.categories;
create policy categories_select on public.categories for select using (true);
drop policy if exists locations_select on public.locations;
create policy locations_select on public.locations for select using (true);

-- news
drop policy if exists news_select on public.news;
create policy news_select on public.news for select
  using (status = 'published' or journalist_id = public.my_profile_id() or public.is_staff());
drop policy if exists news_insert on public.news;
create policy news_insert on public.news for insert
  with check (
    (journalist_id = public.my_profile_id() and public.my_role() = 'journalist'
       and public.is_verified_journalist() and status in ('draft', 'review'))
    or public.my_role() = 'admin'
  );
-- Сэтгүүлч зөвхөн өөрийн «Ноорог» / «Буцаагдсан» мэдээг засаж, «Ноорог» эсвэл «Хянагдаж буй» болгоно
drop policy if exists news_update on public.news;
create policy news_update on public.news for update
  using (
    (journalist_id = public.my_profile_id() and status in ('draft', 'returned'))
    or public.is_staff()
  )
  with check (
    (journalist_id = public.my_profile_id() and public.is_verified_journalist() and status in ('draft', 'review'))
    or public.is_staff()
  );

-- media
drop policy if exists media_select on public.media;
create policy media_select on public.media for select
  using (exists (select 1 from public.news n where n.id = news_id));
drop policy if exists media_insert on public.media;
create policy media_insert on public.media for insert
  with check (exists (select 1 from public.news n where n.id = news_id
                      and (n.journalist_id = public.my_profile_id() or public.is_staff())));
drop policy if exists media_delete on public.media;
create policy media_delete on public.media for delete
  using (exists (select 1 from public.news n where n.id = news_id
                 and (n.journalist_id = public.my_profile_id() or public.is_staff())));

-- decisions: сэтгүүлч өөрийн мэдээний шийдвэрийг харна; зөвхөн редактор шийдвэр гаргана
drop policy if exists decisions_select on public.decisions;
create policy decisions_select on public.decisions for select
  using (public.is_staff() or exists (select 1 from public.news n where n.id = news_id
                                       and n.journalist_id = public.my_profile_id()));
drop policy if exists decisions_insert on public.decisions;
create policy decisions_insert on public.decisions for insert
  with check (public.my_role() = 'editor' and editor_id = public.my_profile_id());

-- news_versions
drop policy if exists versions_select on public.news_versions;
create policy versions_select on public.news_versions for select
  using (public.is_staff() or exists (select 1 from public.news n where n.id = news_id
                                       and n.journalist_id = public.my_profile_id()));
drop policy if exists versions_insert on public.news_versions;
create policy versions_insert on public.news_versions for insert
  with check (user_id = public.my_profile_id()
              and exists (select 1 from public.news n where n.id = news_id
                          and (n.journalist_id = public.my_profile_id() or public.is_staff())));
drop policy if exists versions_delete on public.news_versions;
create policy versions_delete on public.news_versions for delete
  using (user_id = public.my_profile_id());

-- notifications: өөрийнхөө мэдэгдлийг харна; нэвтэрсэн хэрэглэгч бусдад мэдэгдэл илгээж болно
drop policy if exists notifications_select on public.notifications;
create policy notifications_select on public.notifications for select
  using (user_id = public.my_profile_id());
drop policy if exists notifications_insert on public.notifications;
create policy notifications_insert on public.notifications for insert
  with check (public.my_profile_id() is not null);
drop policy if exists notifications_update on public.notifications;
create policy notifications_update on public.notifications for update
  using (user_id = public.my_profile_id()) with check (user_id = public.my_profile_id());

-- external_data, app_settings: бүгд уншина, админ өөрчилнө
